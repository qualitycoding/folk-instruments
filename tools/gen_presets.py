#!/usr/bin/env python3
"""Turn presets/*.json into core/src/generated/presets_data.h (plan/DECISIONS.md D-011, D-020 to D-023, D-030, D-070 to D-073).

  gen_presets.py          write the header
  gen_presets.py --check  exit 0 if the committed header matches the JSON files (integers and strings exactly,
                          floating-point values within a relative 1e-12), 1 if not, 2 on a missing field.
"""
import json, math, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "core/src/generated/presets_data.h"
WITH_CLAIMS = ["harmonica", "accordion", "strings", "bodies"]
WITHOUT_CLAIMS = ["params", "reeds", "gains", "factory"]


def load(name, claims):
    p = ROOT / "presets" / f"{name}.json"
    if not p.exists():
        return None
    d = json.loads(p.read_text())
    if claims:
        for k, e in d.items():
            if not isinstance(e, dict) or not all(f in e for f in ("value", "claim", "confidence")):
                sys.exit(f"gen_presets: {name}.json: entry '{k}' needs value, claim and confidence")
    return d


def num(x):
    return repr(float(x))


def ints(vals):
    return "{" + ", ".join(str(int(x)) for x in vals) + "}"


def halfband():
    from scipy.signal import firwin
    return firwin(63, 0.5, window=("kaiser", 8.6))


def string_spec(s, scale, ratio, rho, tension):
    d_out = s["outer_in"] * 0.0254
    f = 440.0 * 2 ** ((s["midi"] - 69) / 12)
    if s["wound"]:
        return s["midi"], d_out * ratio, True, tension / (4.0 * scale * scale * f * f)
    return s["midi"], d_out, False, rho * math.pi * d_out * d_out / 4.0


def generate():
    L = ["// GENERATED by tools/gen_presets.py from presets/*.json. Do not edit by hand.", "#pragma once", "namespace folk { namespace gen {"]
    h, a, s = (load(n, True) for n in ("harmonica", "accordion", "strings"))
    for k in ("richter_blow_c", "richter_draw_c", "max_bend_draw_holes_1_to_10", "max_bend_blow_holes_1_to_10",
              "overblow_holes", "overdraw_holes", "chromatic_blow_offsets_per_group", "chromatic_draw_offsets_per_group"):
        L.append(f"inline constexpr int kHarp_{k}[] = {ints(h[k]['value'])};")
    for k in ("key_hole1_blow_high_keys_0_to_6", "key_hole1_blow_low_keys_7_to_11", "chromatic_first_note", "chromatic_holes"):
        L.append(f"inline constexpr int kHarp_{k} = {int(h[k]['value'])};")
    bits = a["rank_bits"]["value"]
    regs = a["registers"]["value"]
    L.append("inline constexpr unsigned kAccRanks[] = {" + ", ".join(str(sum(bits[r] for r in g["ranks"])) for g in regs) + "};")
    L.append("inline constexpr const char* kAccNames[] = {" + ", ".join(json.dumps(g["name"]) for g in regs) + "};")
    rho, ten, ratio = s["steel_density"]["value"], s["wound_nominal_tension_n"]["value"], s["wound_core_fraction"]["value"]
    for inst, scales, courses in (("Mandolin", s["mandolin_scale_m"]["value"], s["mandolin_courses"]["value"]),
                                  ("Bouzouki", s["bouzouki_scale_m"]["value"], s["bouzouki_courses"]["value"])):
        L.append(f"inline constexpr double k{inst}Scale[] = {{" + ", ".join(num(x) for x in scales) + "};")
        for v, variant in enumerate(courses):
            rows = []
            for c in variant:
                parts = []
                for key in ("first", "second"):
                    m, d, w, mu = string_spec(c[key], scales[v], ratio, rho, ten)
                    parts.append(f"{{{m}, {num(d)}, {'true' if w else 'false'}, {num(mu)}}}")
                rows.append("{" + ", ".join(parts) + "}")
            L.append(f"inline constexpr StringSpecData k{inst}Courses{v}[] = {{" + ", ".join(rows) + "};")
            L.append(f"inline constexpr int k{inst}Courses{v}Count = {len(variant)};")
    params = load("params", False)
    if params is not None:
        L.append("struct ParamRow { const char* id; const char* name; float min, max, def; int steps; };")
        for i, n in enumerate(params["instruments"]):
            rows = []
            for pid, lo, hi, de, st in params[n]:
                name = pid.replace("_", " ").capitalize().replace(" hz", " Hz")
                rows.append("{" + f'"{pid}", "{name}", {float(lo)!r}f, {float(hi)!r}f, {float(de)!r}f, {int(st)}' + "}")
            L.append(f"inline constexpr ParamRow kParams{i}[] = {{" + ", ".join(rows) + "};")
            L.append(f"inline constexpr int kParams{i}Count = {len(rows)};")
    reeds = load("reeds", False)
    if reeds is not None:
        L.append(f"inline constexpr double kSourceRmsRef = {num(reeds['source_rms_ref'])};")
        L.append("inline constexpr int kReedRates[4] = {44100, 48000, 88200, 96000};")
        for i, n in enumerate(("harmonica", "accordion", "melodion")):
            rows = ["{" + ", ".join(num(x) for x in reeds["offsets"][n][str(r)]) + "}" for r in (44100, 48000, 88200, 96000)]
            L.append(f"inline constexpr double kReedOffsets{i}[4][85] = {{" + ", ".join(rows) + "};")
    gains = load("gains", False) or {}
    order = ["harmonica", "accordion", "melodion", "mandolin", "bouzouki"]
    L.append("inline constexpr double kGainOut[5] = {" + ", ".join(num(gains.get(n, 1.0)) for n in order) + "};")
    hb = halfband()
    L.append("inline constexpr double kHalfBand63[63] = {" + ", ".join(num(x) for x in hb) + "};")
    L.append("}}  // namespace folk::gen")
    # StringSpecData must be declared before use: insert after the namespace line.
    decl = "struct CourseSpecData { struct S { int midi; double diameterM; bool wound; double linearDensity; } first, second; };"
    text = "\n".join(L).replace("StringSpecData", "CourseSpecData")
    text = text.replace("namespace folk { namespace gen {", "namespace folk { namespace gen {\n" + decl, 1)
    return text + "\n"


TOKEN = re.compile(r"-?\d+\.\d*(?:[eE][-+]?\d+)?|-?\d+[eE][-+]?\d+")


def same(a, b):
    ta, tb = TOKEN.findall(a), TOKEN.findall(b)
    if TOKEN.sub("#", a) != TOKEN.sub("#", b) or len(ta) != len(tb):
        return False
    return all(math.isclose(float(x), float(y), rel_tol=1e-12, abs_tol=1e-300) for x, y in zip(ta, tb))


def main(argv):
    text = generate()
    if "--check" in argv:
        if not OUT.exists() or not same(OUT.read_text(), text):
            print("gen_presets: committed header does not match presets/*.json", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
